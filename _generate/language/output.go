func generate(sourceDir string, outputPath string, packageName string) error {
	catalog, err := readCatalog(sourceDir)
	if err != nil {
		return err
	}

	data, err := render(catalog, packageName)
	if err != nil {
		return err
	}

	return writeAtomic(outputPath, data)
}
