func sortedKeys(values map[string]string) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func render(catalog catalogObj, packageName string) ([]byte, error) {
	if !token.IsIdentifier(packageName) || token.Lookup(packageName).IsKeyword() {
		return nil, fmt.Errorf("invalid package name %q", packageName)
	}

	var output bytes.Buffer
	output.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	fmt.Fprintf(&output, "package %s\n\n", packageName)

	output.WriteString("var keys = []string{\n")
	for _, entry := range catalog.entries {
		fmt.Fprintf(&output, "\t%s,\n", strconv.Quote(entry.key))
	}
	output.WriteString("}\n\n")

	output.WriteString("var names = map[string]string{\n")
	for _, entry := range catalog.entries {
		fmt.Fprintf(&output, "\t%s: %s,\n", strconv.Quote(entry.key), strconv.Quote(entry.name))
	}
	output.WriteString("}\n\n")

	output.WriteString("var values = map[string]map[string]string{\n")
	for _, entry := range catalog.entries {
		fmt.Fprintf(&output, "\t%s: {\n", strconv.Quote(entry.key))
		for _, key := range sortedKeys(entry.values) {
			fmt.Fprintf(&output, "\t\t%s: %s,\n", strconv.Quote(key), strconv.Quote(entry.values[key]))
		}
		output.WriteString("\t},\n")
	}
	output.WriteString("}\n")

	output.WriteString(`
func Keys() []string {
	return append([]string(nil), keys...)
}

func Name(key string) (string, bool) {
	name, ok := names[key]
	return name, ok
}

func Supports(key string) bool {
	_, ok := values[key]
	return ok
}

func Get(languageKey string, translationKey string) (string, bool) {
	translations, ok := values[languageKey]
	if !ok {
		return "", false
	}

	value, ok := translations[translationKey]
	return value, ok
}
`)

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}

	return formatted, nil
}

func writeAtomic(path string, data []byte) error {
	existing, err := os.ReadFile(path)
	if err == nil && bytes.Equal(existing, data) {
		return nil
	}
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read existing output: %w", err)
	}

	directory := filepath.Dir(path)
	if err = os.MkdirAll(directory, 0755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}

	file, err := os.CreateTemp(directory, "."+filepath.Base(path)+".*")
	if err != nil {
		return fmt.Errorf("create temporary output: %w", err)
	}
	temporaryPath := file.Name()
	closed := false
	defer func() {
		if !closed {
			_ = file.Close()
		}
		_ = os.Remove(temporaryPath)
	}()

	if err = file.Chmod(0644); err != nil {
		return fmt.Errorf("set output permissions: %w", err)
	}
	if _, err = file.Write(data); err != nil {
		return fmt.Errorf("write temporary output: %w", err)
	}
	if err = file.Sync(); err != nil {
		return fmt.Errorf("sync temporary output: %w", err)
	}
	if err = file.Close(); err != nil {
		return fmt.Errorf("close temporary output: %w", err)
	}
	closed = true

	if err = os.Rename(temporaryPath, path); err != nil {
		return fmt.Errorf("replace output: %w", err)
	}

	return nil
}

